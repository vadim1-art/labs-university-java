package model;

/**
 * Сущность, у которой есть идентификатор.
 * Благодаря этому интерфейсу обобщенный репозиторий может достать ключ
 * у любого объекта (транзакции, кошелька ...), не зная его конкретного класса.
 *
 * @param <ID> тип идентификатора (UUID, String, Long ...)
 */
public interface Identifiable<ID> {
    ID getId();
}
